import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { readFile, access } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const directory=resolve(process.env.PAM_WEBVIEW_REPORT_DIR||join(root,'artifacts','webview-cleanup',String(Date.now())));
const child=spawn(process.execPath,[join(root,'scripts/test-modals.mjs')],{cwd:root,windowsHide:true,stdio:'inherit',env:{...process.env,PAM_WEBVIEW_REPORT_DIR:directory,PAM_WEBVIEW_INJECT_FAILURE:'1'}});
const code=await new Promise((done,reject)=>{child.once('error',reject);child.once('exit',done);});
assert.equal(code,1,'Injected runner failure must fail the command');
const report=JSON.parse(await readFile(join(directory,'report.json'),'utf8'));
assert.equal(report.outcome,'failed');assert.match(report.error,/intentional runner failure/);
assert.deepEqual(report.cleanup.audio,{liveTracks:0,openContexts:0});
assert.equal(report.cleanup.audioBefore.contexts,1,'The failed page owned a real AudioContext');
assert.equal(report.cleanup.hostExited,true);assert.equal(report.cleanup.serverClosed,true);assert.equal(report.cleanup.profileRemoved,true);
assert.deepEqual(report.cleanup.errors,[]);
await assert.rejects(access(report.profile),{code:'ENOENT'});
await access(join(directory,'failure.png'));await access(join(directory,'failure-dom.html'));
assert.throws(()=>process.kill(report.pid,0),{code:'ESRCH'});
console.log('PASS intentional WebView2 failure: nonzero exit, diagnostics, audio, process and profile cleanup');
