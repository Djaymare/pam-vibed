import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm, mkdir } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createRequire } from 'node:module';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { encodeWav } = await import('../src/audio/wav.ts');
const { createAssistant } = require('../sidecar/assistant.cjs');
const { createEngine } = require('../sidecar/engine.cjs');
const run = promisify(execFile);
assert.equal(process.platform, 'win32', 'Ce test vérifie les binaires Windows réels.');
const cache = join(root, '.runtime-cache');
await mkdir(cache, { recursive: true });
const temporary = await mkdtemp(join(cache, 'smoke-'));
const engine = createEngine(join(root, 'src-tauri/runtime'));
try {
  const node = join(root, 'src-tauri/binaries/pam-node-x86_64-pc-windows-msvc.exe');
  const runtimeDirectory = join(root, 'src-tauri/runtime');
  const handle = createAssistant({ configDirectory: temporary, runtimeDirectory, runEngine: engine.runEngine, engine });
  const status = await handle('status'); assert.equal(status.ready, true);
  assert.equal(status.engine.loaded, true); assert.equal(status.engine.generation, 1);
  const { stdout } = await run(node, [join(runtimeDirectory, 'npm/bin/npm-cli.js'), '--version']);
  assert.ok(stdout.trim()); console.log(`npm embarqué : ${stdout.trim()}`);
  const marker = join(temporary, 'launched.txt');
  const fixture = join(temporary, 'launch.cjs');
  await writeFile(fixture, `require('node:fs').writeFileSync(${JSON.stringify(marker)}, 'launched');`);
  await handle('save_application', { name: 'Bloc-notes', aliases: ['Notepad'], description: 'Ouvrir le Bloc-notes pour écrire et éditer du texte.',
    executable: node, arguments: [fixture], enabled: true });
  await handle('settings', { language: 'fr', autoExecute: false, confidenceThreshold: 0.7 });
  const text = await handle('process_text', { text: 'Ouvre le Bloc-notes' });
  console.log('Needle texte :', JSON.stringify(text));
  assert.equal(text.status, 'pending'); assert.equal(text.calls[0].applicationName, 'Bloc-notes');
  await handle('confirm', { id: text.id });
  // The actual configured executable creates a marker and exits. No user app opens.
  for (let attempt = 0; attempt < 20; attempt++) {
    try { assert.equal(await readFile(marker, 'utf8'), 'launched'); break; }
    catch (error) { if (attempt === 19) throw error; await new Promise(resolve => setTimeout(resolve, 50)); }
  }
  console.log('Exécution réelle et confirmation : OK');
  const silence = await handle('process_audio', { audio: Array.from(encodeWav(new Float32Array(16_000))) });
  assert.equal(silence.status, 'silence'); console.log('Whistle + Needle, silence : OK');
  const unsupported = await handle('process_text', { text: 'Quelle est la météo demain à Tokyo ?' });
  assert.equal(unsupported.status, 'unsupported'); console.log('Demande hors périmètre : OK');
  // Several competing tools reproduce the Diseur -> VS Code regression.
  for (const app of [
    { name: 'Battlefield 6', aliases: ['BF6'], description: 'Jeu de tir' },
    { name: 'Visual Studio Code', aliases: ['VS Code'], description: 'Éditeur de code' },
    { name: 'Deezer', aliases: ['Diseur', 'Musique préférée'], description: 'Plateforme d’écoute de musique en streaming' },
  ]) await handle('save_application', { ...app, executable: node, arguments: [fixture], enabled: true });
  for (const [request, expected] of [
    ['Diseur', 'Deezer'], ['Ouvre Diseur', 'Deezer'], ['DISEUR !', 'Deezer'],
    ['Ouvre l’application Diseur, s’il te plaît.', 'Deezer'], ['Musique préférée', 'Deezer'],
    ['Ouvre Deezer', 'Deezer'], ['VS Code', 'Visual Studio Code'], ['BF6', 'Battlefield 6'],
  ]) {
    const turn = await handle('process_text', { text: request });
    assert.equal(turn.transcript, request);
    assert.equal(turn.status, 'pending');
    assert.deepEqual(turn.calls.map(call => call.applicationName), [expected], request);
    await handle('discard', { id: turn.id });
    console.log(`Alias texte : ${request} → ${expected} : OK`);
  }
  // Optional real speech WAV generated by Windows SAPI or supplied by the caller.
  for (const [file, expected] of [[process.argv[2], 'Bloc-notes'], [process.argv[3], 'Deezer']]) {
    if (!file) continue;
    const speech = await readFile(resolve(file));
    // SAPI adds RIFF metadata and an extended fmt chunk. Normalize that fixture
    // to the same canonical PCM WAV generated by the actual microphone frontend.
    let data;
    for (let offset = 12; offset + 8 <= speech.length;) {
      const size = speech.readUInt32LE(offset + 4);
      if (speech.toString('ascii', offset, offset + 4) === 'data') { data = speech.subarray(offset + 8, offset + 8 + size); break; }
      offset += 8 + size + (size % 2);
    }
    assert.ok(data, 'Fixture WAV sans données audio.');
    const samples = Float32Array.from({ length: data.length / 2 }, (_, index) => data.readInt16LE(index * 2) / 32768);
    const audio = await handle('process_audio', { audio: Array.from(encodeWav(samples)) });
    console.log('Whistle audio parlé :', JSON.stringify(audio));
    assert.ok(audio.transcript.length > 0);
    assert.deepEqual(audio.calls.map(call => call.applicationName), [expected]);
    const fromText = await handle('process_text', { text: audio.transcript });
    assert.deepEqual(audio.calls, fromText.calls);
    assert.equal(audio.confidence, fromText.confidence, 'Le vocal et le texte doivent recevoir le même score Needle pour la même transcription.');
    console.log(`Parité texte/vocal : ${audio.transcript} → ${expected}, confiance Needle ${audio.confidence} : OK`);
  }
  console.log('Intégration Windows réelle : OK');
} finally {
  await engine.close();
  assert.equal(dirname(resolve(temporary)), resolve(cache)); assert.ok(temporary.startsWith(join(cache, 'smoke-')));
  await rm(temporary, { recursive: true, force: true });
}
