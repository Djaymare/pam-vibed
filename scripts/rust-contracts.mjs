// Emit strongly typed Rust data and discriminated calls/results from the same
// descriptor as TypeScript. Runtime schemas enforce literals, bounds and format.
export function rustContracts(contract,hash) {
  const declarations=[],named=new Set();
  const pascal=name=>name.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(p=>p[0].toUpperCase()+p.slice(1)).join('');
  const snake=name=>name.replace(/[A-Z]/g,m=>'_'+m.toLowerCase());
  function type(schema,name) {
    if(typeof schema==='string')return {string:'String',boolean:'bool',number:'f64',integer:'u64',byte:'u8'}[schema]??schema;
    if('literal'in schema)return schema.literal===null?'()':typeof schema.literal==='boolean'?'bool':typeof schema.literal==='number'?'u64':'String';
    if(schema.nullable)return `Option<${type(schema.nullable,name+'Value')}>`;
    if(schema.array)return `Vec<${type(schema.array,name+'Item')}>`;
    if(schema.record)return `std::collections::BTreeMap<String,${type(schema.record,name+'Value')}>`;
    if(named.has(name))return name;
    named.add(name);
    if(schema.enum) {
      declarations.push(`#[derive(Clone,Debug,serde::Serialize,serde::Deserialize)]\npub enum ${name} {\n${schema.enum.map(v=>`#[serde(rename=${JSON.stringify(v)})] ${pascal(v)},`).join('\n')}\n}`);
    } else {
      const fields=Object.entries(schema.properties).map(([key,s])=>{
        const optional=key.endsWith('?'),raw=optional?key.slice(0,-1):key;
        const t=type(s,name+pascal(raw));
        return `${optional?'#[serde(default,skip_serializing_if="Option::is_none")]\n':''}pub ${snake(raw)}: ${optional?`Option<${t}>`:t},`;
      });
      if(schema.extra)fields.push('#[serde(flatten)] pub extra: std::collections::BTreeMap<String,serde_json::Value>,');
      declarations.push(`#[derive(Clone,Debug,serde::Serialize,serde::Deserialize)]\n#[serde(rename_all="camelCase"${schema.extra?'':',deny_unknown_fields'})]\npub struct ${name} {\n${fields.join('\n')}\n}`);
    }
    return name;
  }
  for(const [name,schema]of Object.entries(contract.definitions)) {
    const t=type(schema,name);if(t!==name)declarations.push(`pub type ${name}=${t};`);
  }
  const methods=Object.entries(contract.methods).map(([method,[payload,result]])=>({method,variant:pascal(method),payload:type(payload,pascal(method)+'Payload'),result:type(result,pascal(method)+'Result')}));
  const resultType=t=>t==='String'||t==='()'||t.startsWith('Vec<')||t.startsWith('std::collections::')?t:`Box<${t}>`;
  return `// Generated by scripts/generate-contracts.mjs; edit sidecar/contracts.json.\n// SHA-256 ${hash}\npub const VERSION:u64=${contract.version};\n#[cfg(test)] pub const CONTRACT_SHA256:&str="${hash}";\n${declarations.join('\n')}\n`+
    `#[derive(Clone,Copy,Debug,serde::Serialize,serde::Deserialize)]\npub enum Method {\n${methods.map(m=>`#[serde(rename="${m.method}")] ${m.variant},`).join('\n')}\n}\n`+
    `impl Method {pub fn name(self)->&'static str {match self {${methods.map(m=>`Self::${m.variant}=>"${m.method}",`).join('\n')}}}}\n`+
    `#[derive(Debug,serde::Serialize,serde::Deserialize)]\n#[serde(tag="method",content="payload")]\npub enum Call {\n${methods.map(m=>`#[serde(rename="${m.method}")] ${m.variant}(${m.payload}),`).join('\n')}\n}\n`+
    `impl Call {pub fn method(&self)->Method {match self {${methods.map(m=>`Self::${m.variant}(_)=>Method::${m.variant},`).join('\n')}}}\npub fn payload(&self)->serde_json::Value {match self {${methods.map(m=>`Self::${m.variant}(p)=>serde_json::to_value(p).expect("typed payload"),`).join('\n')}}}}\n`+
    `#[derive(Debug,serde::Serialize,serde::Deserialize)]\n#[serde(tag="method",content="result")]\npub enum MethodResult {\n${methods.map(m=>`#[serde(rename="${m.method}")] ${m.variant}(${resultType(m.result)}),`).join('\n')}\n}\n`+
    `#[derive(Debug,serde::Deserialize)]\n#[serde(rename_all="camelCase")]\npub struct Request {pub version:u64,pub id:u64,pub request_id:String,#[serde(flatten)]pub call:Call}\n`;
}
